const fn build_vlc(src: &[VlcSrc]) -> [u16; 1024] {
    let mut out = [0u16; 1024];
    let mut i = 0;
    while i < 1024 {
        let cwd = (i & 0x7F) as i32;
        let c_q = (i >> 7) as i32;
        let mut j = 0;
        while j < src.len() {
            let e = src[j];
            if e[0] == c_q && e[5] == (cwd & ((1 << e[6]) - 1)) {
                out[i] = ((e[1] << 4) | (e[2] << 3) | (e[3] << 12) | (e[4] << 8) | e[6]) as u16;
            }
            j += 1;
        }
        i += 1;
    }
    out
}

